import os
import requests
import httpx
import json
import logging

# Connect native Uvicorn-safe routing
logger = logging.getLogger(__name__)

# OS-Level Environment Mapping
LLM_API_URL = os.getenv("OLLAMA_API_URL", "http://localhost:11434/api/chat")

# Optimization: Persistent TCP Connection Pipeline
session = requests.Session()
async_client = httpx.AsyncClient(timeout=120.0)

def generate_rag_response(messages: list[dict[str, str]], model_name: str = None) -> str:
    """
    Sub-Module 3.4: The Generative Engine
    Transmits the mathematically fenced context to the local LLM socket.
    """
    if not messages:
        logger.error("[ERROR] Generative Engine received an empty messages array and aborted network transmission.")
        return "System Error: The system aborted generation because no context was successfully built."
        
    # Evaluate model_name at execution time to allow dynamic OS Environment overrides!
    active_model = model_name if model_name else os.getenv("OLLAMA_MODEL", "llama3.2")
    
    payload = {
        "model": active_model,
        "messages": messages,
        "stream": False, 
        "keep_alive": "15m", # Optimization 1: Prevents 30s cold-start delays across queries
        "options": {
            "temperature": 0.1,  
            "num_predict": 512,
            "num_ctx": 4096,     
            "top_p": 0.9         
        }
    }
    
    try:
        # Note: 120s timeout is critical! Cold-starting models into your 16GB RAM can take ~30s on the first prompt.
        response = session.post(LLM_API_URL, json=payload, timeout=120.0)
        
        if response.status_code != 200:
            logger.error(f"[ERROR] LLM API Status {response.status_code} -> {response.text}")
            return f"System Error: LLM Engine returned status {response.status_code}."
            
        return response.json().get("message", {}).get("content", "").strip()

    except requests.exceptions.ConnectionError as e:
        logger.error(f"[ERROR] Ollama Connection Failed: {str(e)}")
        return f"System Error: Cannot connect to {LLM_API_URL}. Is Ollama running?"
    except requests.exceptions.Timeout as e:
        logger.error(f"[ERROR] Ollama Thermal Timeout: {str(e)}")
        return "System Error: Inference timeout. Model took too long to load into RAM."
    except requests.exceptions.JSONDecodeError as e:
        logger.error(f"[ERROR] Ollama Malformed Output: {str(e)}")
        return "System Error: Local AI returned invalid parsing data natively."
    except Exception as e:
        logger.error(f"[ERROR] Unexpected Execution Crash: {str(e)}")
        return "System Error: Unexpected failure. See the server log for details."

async def generate_rag_response_stream(messages: list[dict[str, str]], model_name: str = None, settings: dict = None):
    """
    Sub-Module 3.4 (Streaming): Async Token Streamer
    Yields JSON string tokens generated by Ollama or Cloud LLMs over SSE.
    """
    if not messages:
        logger.error("[ERROR] Generative Engine received an empty messages array and aborted stream.")
        yield json.dumps({"type": "token", "content": "System Error: No context was successfully built."})
        return

    # Default to ollama if settings aren't provided
    settings = settings or {}
    provider = settings.get("provider", "ollama")
    
    formatted_messages = messages if isinstance(messages, list) else [{"role": "user", "content": str(messages)}]

    if provider == "openai":
        api_key = settings.get("openai_key")
        if not api_key:
            yield json.dumps({"type": "token", "content": "System Error: OpenAI API Key is missing. Please configure it in settings."})
            return
            
        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json"
        }
        payload = {
            "model": "gpt-4o-mini", # Or allow this to be configurable
            "messages": formatted_messages,
            "stream": True,
            "temperature": 0.1
        }
        
        try:
            async with async_client.stream("POST", url, json=payload, headers=headers) as response:
                if response.status_code != 200:
                    error_text = await response.aread()
                    logger.error(f"[ERROR] OpenAI API Status {response.status_code} -> {error_text.decode('utf-8', errors='ignore')}")
                    yield json.dumps({"type": "token", "content": f"System Error: OpenAI returned status {response.status_code}."})
                    return

                async for line in response.aiter_lines():
                    if line.startswith("data: "):
                        data_str = line[6:].strip()
                        if data_str == "[DONE]":
                            break
                        try:
                            data = json.loads(data_str)
                            choices = data.get("choices", [])
                            if choices:
                                content = choices[0].get("delta", {}).get("content", "")
                                if content:
                                    yield json.dumps({"type": "token", "content": content})
                        except Exception as parse_err:
                            logger.error(f"[ERROR] OpenAI Stream parse error: {parse_err}")
        except Exception as e:
            logger.error(f"[ERROR] OpenAI Execution Crash: {str(e)}")
            yield json.dumps({"type": "token", "content": "System Error: Unexpected failure. See the server log for details."})
            
    elif provider == "anthropic":
        api_key = settings.get("anthropic_key")
        if not api_key:
            yield json.dumps({"type": "token", "content": "System Error: Anthropic API Key is missing. Please configure it in settings."})
            return
            
        url = "https://api.anthropic.com/v1/messages"
        headers = {
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json"
        }
        
        # Anthropic expects 'system' parameter for system prompts natively, but formatting everything as role-based works if structured properly.
        # Ensure no system roles are sent inside messages to Anthropic unless using the top-level 'system' param.
        anthropic_messages = []
        system_text = ""
        for m in formatted_messages:
            if m["role"] == "system":
                system_text += m["content"] + "\n"
            else:
                anthropic_messages.append(m)

        payload = {
            "model": "claude-3-haiku-20240307",
            "max_tokens": 1024,
            "messages": anthropic_messages,
            "stream": True,
            "temperature": 0.1
        }
        if system_text:
            payload["system"] = system_text.strip()
            
        try:
            async with async_client.stream("POST", url, json=payload, headers=headers) as response:
                if response.status_code != 200:
                    error_text = await response.aread()
                    logger.error(f"[ERROR] Anthropic API Status {response.status_code} -> {error_text.decode('utf-8', errors='ignore')}")
                    yield json.dumps({"type": "token", "content": f"System Error: Anthropic returned status {response.status_code}."})
                    return

                event_type = None
                async for line in response.aiter_lines():
                    if line.startswith("event: "):
                        event_type = line[7:].strip()
                    elif line.startswith("data: "):
                        data_str = line[6:].strip()
                        if not data_str:
                            continue
                        try:
                            data = json.loads(data_str)
                            if event_type == "content_block_delta":
                                content = data.get("delta", {}).get("text", "")
                                if content:
                                    yield json.dumps({"type": "token", "content": content})
                        except Exception as parse_err:
                            logger.error(f"[ERROR] Anthropic Stream parse error: {parse_err}")
        except Exception as e:
            logger.error(f"[ERROR] Anthropic Execution Crash: {str(e)}")
            yield json.dumps({"type": "token", "content": "System Error: Unexpected failure. See the server log for details."})

    else:
        # Default Ollama behavior
        active_model = settings.get("ollama_model") or os.getenv("OLLAMA_MODEL", "llama3.2")
        payload = {
            "model": active_model,
            "messages": formatted_messages,
            "stream": True,
            "keep_alive": "15m",
            "options": {
                "temperature": 0.1,
                "num_predict": 512,
                "num_ctx": 4096,
                "top_p": 0.9
            }
        }

        try:
            async with async_client.stream("POST", LLM_API_URL, json=payload) as response:
                if response.status_code != 200:
                    error_text = await response.aread()
                    logger.error(f"[ERROR] LLM API Status {response.status_code} -> {error_text.decode('utf-8', errors='ignore')}")
                    yield json.dumps({"type": "token", "content": f"System Error: LLM Engine returned status {response.status_code}."})
                    return

                async for line in response.aiter_lines():
                    if line:
                        try:
                            data = json.loads(line)
                            content = data.get("message", {}).get("content", "")
                            if content:
                                yield json.dumps({"type": "token", "content": content})
                        except Exception as parse_err:
                            logger.error(f"[ERROR] Ollama Stream parse error: {parse_err}")
        except httpx.ConnectError as e:
            logger.error(f"[ERROR] Ollama Connection Failed: {str(e)}")
            yield json.dumps({"type": "token", "content": f"System Error: Cannot connect to {LLM_API_URL}. Is Ollama running?"})
        except httpx.TimeoutException as e:
            logger.error(f"[ERROR] Ollama Thermal Timeout: {str(e)}")
            yield json.dumps({"type": "token", "content": "System Error: Inference timeout. Model took too long to load into RAM."})
        except Exception as e:
            logger.error(f"[ERROR] Unexpected Execution Crash: {str(e)}")
            yield json.dumps({"type": "token", "content": "System Error: Unexpected failure. See the server log for details."})

